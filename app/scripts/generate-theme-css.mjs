#!/usr/bin/env node
/**
 * Writes the colour tokens from src/constants/color-tokens.ts into the
 * generated block of src/global.css, so Tailwind/Uniwind classes use them.
 *
 *   npm run theme:generate   rewrite the block
 *   npm run theme:check      fail if the block is out of date (use in CI)
 *
 * Needs Node 22.18+ (imports the .ts token file via built-in type stripping).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { cssVariableName, resolveColors, tokenNames } from '../src/constants/color-tokens.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = join(root, 'src', 'global.css');
const START = '/* <color-tokens> generated by scripts/generate-theme-css.mjs from src/constants/color-tokens.ts. Do not edit by hand. */';
const END = '/* </color-tokens> */';

// Every alias is resolved to its final colour (V2 primitives are private and never emitted).
const names = tokenNames();
const seen = new Map();
for (const name of names) {
  const css = cssVariableName(name);
  if (seen.has(css)) {
    console.error(`Tokens "${seen.get(css)}" and "${name}" both map to ${css}.`);
    process.exit(1);
  }
  seen.set(css, name);
}

const variant = (theme) => {
  const colors = resolveColors(theme);
  return names.map((name) => `      ${cssVariableName(name)}: ${colors[name]};`).join('\n');
};

const block = `${START}
@layer theme {
  :root {
    @variant light {
${variant('light')}
    }
    @variant dark {
${variant('dark')}
    }
  }
}
${END}`;

const css = readFileSync(cssPath, 'utf8');
const start = css.indexOf(START);
const end = css.indexOf(END);
if (start === -1 || end === -1) {
  console.error(`Could not find the <color-tokens> markers in ${cssPath}.`);
  process.exit(1);
}
const next = css.slice(0, start) + block + css.slice(end + END.length);

if (process.argv.includes('--check')) {
  if (next !== css) {
    console.error('src/global.css colour tokens are out of date. Run `npm run theme:generate`.');
    process.exit(1);
  }
  console.log('Colour tokens are up to date.');
} else {
  writeFileSync(cssPath, next);
  console.log(`Wrote ${names.length} colour tokens (light + dark) to src/global.css.`);
}
